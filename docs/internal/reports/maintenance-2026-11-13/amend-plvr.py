from pathlib import Path
from copy import deepcopy
from datetime import datetime,timezone
import hashlib,json,shutil
from scripts.common import read_yaml
from scripts.feed.storage import load_items,write_json
from scripts.feed.review import validate_daily_review,source_hash
from scripts.feed.digest import _json,_render_edition,_published,_directions,_write_feed

R=Path.cwd(); B=R/'build/maintenance-2026-11-13'; D=R/'docs/internal/reports/maintenance-2026-11-13'
ident='arxiv:2610.19148';path=R/'site/weekly/2026-W45.json';before=json.loads(path.read_text())
baseline=json.loads((B/'preservation-baseline.json').read_text())
for name,sha in baseline['w45'].items():
    p=R/name;assert hashlib.sha256(p.read_bytes()).hexdigest()==sha,name
    t=D/'prior-editions'/name;t.parent.mkdir(parents=True,exist_ok=True)
    if t.exists():assert t.read_bytes()==p.read_bytes()
    else:shutil.copyfile(p,t)
receipt=next(x for x in json.loads((B/'publication-generation.json').read_text()) if x.get('date')=='2026-11-13')
assert ident in receipt['applied_ids']
review=validate_daily_review(R,'2026-11-13');row=next(x for x in review['items'] if x['id']==ident)
item=next(x for x in load_items(R) if x['id']==ident)
assert row['source_hash']==source_hash(item)==item['review']['source_hash']
assert item['review']['github_pr']==receipt['github_pr'] and item['review']['merge_commit']==receipt['merge_commit']
assert row['decision']=='backlog' and item['version']==1
edition=deepcopy(before);entry=next(x for x in edition['backlog'] if x['id']==ident)
old_summary={k:entry[k] for k in ['summary_zh','summary_en']}
entry.update(row['summary_override'])
pr=receipt['github_pr'];stamp=datetime.now(timezone.utc).isoformat(timespec='seconds').replace('+00:00','Z')
note_zh=f'勘误（2026-11-13）：PLVR v1 的原语和规则库依赖人工种子与前沿模型从教师轨迹生成。此次只修正摘要来源归属，版本、原始结果与本期选择保持。审核凭据：PR #{pr}。'
note_en=f'Correction (2026-11-13): PLVR v1 relies on handwritten seeds and primitives and rules generated by frontier models from teacher traces. Only the summary attribution is corrected; the version, original results and edition selections are retained. Review receipt: PR #{pr}.'
edition['editor_note_zh']=(edition['editor_note_zh']+'\n\n'+note_zh).strip()
edition['editor_note_en']=(edition['editor_note_en']+'\n\n'+note_en).strip()
edition['updated_at']=stamp
for section in ['items','backlog','picks','lab_updates']:
    assert len(edition[section])==len(before[section])
    for old,new in zip(before[section],edition[section]):
        if section=='backlog' and old['id']==ident:
            assert {k:v for k,v in old.items() if k not in row['summary_override']}=={k:v for k,v in new.items() if k not in row['summary_override']}
        else:assert old==new
_json(path,edition);config=read_yaml(R/'site.config.yaml');directions=_directions(read_yaml(R/'feed/taxonomy.yaml'))
_render_edition(R,edition,_published(R,'weekly'),directions,config)
_write_feed(R,_published(R,'weekly'),config,{x['id'] for x in load_items(R) if x.get('retracted')})
out={'id':ident,'version':1,'edition':'2026-W45','reviewed_on':'2026-11-13','amended_at':stamp,
     'github_pr':pr,'owner_login':receipt['owner_login'],'merge_commit':receipt['merge_commit'],
     'review_sha256':receipt['review_sha256'],'source_hash':row['source_hash'],
     'old_summary':old_summary,'corrected_summary':row['summary_override'],
     'old_manifest_sha256':baseline['w45']['site/weekly/2026-W45.json'],
     'new_manifest_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
     'changed_manifest_fields':['backlog[arxiv:2610.19148].summary_zh','backlog[arxiv:2610.19148].summary_en','editor_note_zh','editor_note_en','updated_at'],
     'other_items_picks_dates_metrics_and_counts_unchanged':True,'full_week_reselection':False,
     'boundary':'Narrow local erratum rendered after verified date-review merge; public deployment still requires publication PR and HTTP checks.'}
write_json(B/'plvr-weekly-erratum.json',out);write_json(D/'plvr-weekly-erratum.json',out)
print({'week':'2026-W45','id':ident,'approved_pr':pr,'other_items_unchanged':True})
